import { execSync } from 'node:child_process';
import { PrismaClient } from '@prisma/client';
import { TEST_ADMIN_URL, TEST_DB_NAME, testEnv } from './test-env.js';

/**
 * Runs once around the whole suite.
 *
 * Creates a fresh, uniquely named database, applies every migration with
 * `migrate deploy` (the same command production runs at start-up, including
 * the raw-SQL search columns and triggers Prisma cannot express), loads the
 * development seed into it, and drops it again when the suite finishes.
 *
 * Going through the real migrations rather than `prisma db push` is the point:
 * a migration that does not apply cleanly fails here, not on deploy.
 */
export default async function setup(): Promise<() => Promise<void>> {
  const admin = new PrismaClient({ datasourceUrl: TEST_ADMIN_URL });
  // The name is generated by test-env.ts and validated against a strict
  // pattern there, so interpolating it is safe.
  await admin.$executeRawUnsafe(`CREATE DATABASE "${TEST_DB_NAME}"`);

  const env = { ...process.env, ...testEnv };
  const run = (command: string) => execSync(command, { env, stdio: 'pipe' });

  try {
    run('npx prisma migrate deploy');
    run('npx tsx prisma/seed.ts');
  } catch (error) {
    await drop(admin);
    throw error;
  }

  return async () => {
    await drop(admin);
  };
}

async function drop(admin: PrismaClient): Promise<void> {
  try {
    await admin.$executeRawUnsafe(`DROP DATABASE IF EXISTS "${TEST_DB_NAME}" WITH (FORCE)`);
  } finally {
    await admin.$disconnect();
  }
}
